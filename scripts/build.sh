#!/bin/bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BUILD="${POINTSWOMAN_BUILD_DIR:-$ROOT/.build}"
export CLANG_MODULE_CACHE_PATH="${CLANG_MODULE_CACHE_PATH:-$BUILD/clang-cache}"
export SWIFT_MODULECACHE_PATH="${SWIFT_MODULECACHE_PATH:-$BUILD/swift-cache}"
swift build --build-system native --disable-sandbox --cache-path "$BUILD/cache" --config-path "$BUILD/config" --security-path "$BUILD/security" --package-path "$ROOT" --scratch-path "$BUILD" -c release
BIN="$(swift build --build-system native --disable-sandbox --cache-path "$BUILD/cache" --config-path "$BUILD/config" --security-path "$BUILD/security" --package-path "$ROOT" --scratch-path "$BUILD" -c release --show-bin-path)"
APP="$ROOT/dist/PointsWoman.app"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources" "$ROOT/dist"
cp "$BIN/PointsWoman" "$APP/Contents/MacOS/PointsWoman"
cp "$BIN/pointswomanctl" "$APP/Contents/MacOS/pointswomanctl"
cp "$ROOT/Resources/Info.plist" "$APP/Contents/Info.plist"
swift "$ROOT/scripts/make-icon.swift" "$BUILD/PointsWoman.iconset" "$ROOT/Resources/PointsWoman.png"
iconutil -c icns "$BUILD/PointsWoman.iconset" -o "$ROOT/Resources/PointsWoman.icns"
cp "$ROOT/Resources/PointsWoman.icns" "$APP/Contents/Resources/PointsWoman.icns"
cp "$BIN/pointswomanctl" "$ROOT/dist/pointswomanctl"
cp "$ROOT/scripts/Restore PointsWoman.command" "$ROOT/dist/Restore PointsWoman.command"
cp "$ROOT/scripts/Install CLI.command" "$ROOT/dist/Install CLI.command"
chmod +x "$ROOT/dist/Restore PointsWoman.command"
chmod +x "$ROOT/dist/Install CLI.command"
strip -x "$APP/Contents/MacOS/PointsWoman"
strip -x "$APP/Contents/MacOS/pointswomanctl"
strip -x "$ROOT/dist/pointswomanctl"
codesign --force --sign - "$APP/Contents/MacOS/pointswomanctl"
codesign --force --sign - "$APP"
codesign --verify --deep --strict "$APP"
ditto -c -k --sequesterRsrc --keepParent "$APP" "$ROOT/dist/PointsWoman-app.zip"
BUNDLE="$BUILD/PointsWoman-macOS"
mkdir -p "$BUNDLE"
ditto "$APP" "$BUNDLE/PointsWoman.app"
cp "$ROOT/dist/pointswomanctl" "$ROOT/dist/Restore PointsWoman.command" "$ROOT/dist/Install CLI.command" "$BUNDLE/"
cp "$ROOT/README.md" "$ROOT/QUICKSTART.txt" "$BUNDLE/"
if [ -f "$ROOT/TEST-RESULTS.md" ]; then cp "$ROOT/TEST-RESULTS.md" "$BUNDLE/"; fi
ditto -c -k --sequesterRsrc --keepParent "$BUNDLE" "$ROOT/dist/PointsWoman-macOS-$(uname -m).zip"
echo "Built: $APP"
echo "Local ad-hoc signature only; no Apple notarization or paid membership."
